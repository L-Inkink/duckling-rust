#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_spring_festival_range() {
        // 春节必在1月21日至2月20日之间
        for &(year, month, day) in SPRING_FESTIVAL {
            assert!(
                (month == 1 && day >= 21) || (month == 2 && day <= 20),
                "Year {} has invalid spring festival date: {}/{}",
                year, month, day
            );
        }
    }

    #[test]
    fn test_qingming_range() {
        // 清明必在4月4-6日
        for &(year, month, day) in QINGMING {
            assert_eq!(month, 4, "Qingming year {} not in April", year);
            assert!(
                day >= 4 && day <= 6,
                "Qingming year {} day {} not in range 4-6",
                year, day
            );
        }
    }

    #[test]
    fn test_data_coverage() {
        assert_eq!(SPRING_FESTIVAL.len(), 101); // 1950-2050
        assert_eq!(QINGMING.len(), 51);         // 2000-2050
        assert_eq!(DRAGON_BOAT.len(), 51);      // 2000-2050
        assert_eq!(MID_AUTUMN.len(), 51);       // 2000-2050
    }

    #[test]
    fn test_known_dates() {
        // 验证2024年的节日日期（可在线查询确认）
        assert!(SPRING_FESTIVAL.contains(&(2024, 2, 10)));
        assert!(QINGMING.contains(&(2024, 4, 4)));
        assert!(DRAGON_BOAT.contains(&(2024, 6, 10)));
        assert!(MID_AUTUMN.contains(&(2024, 9, 17)));
    }
}
